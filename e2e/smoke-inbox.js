const { chromium } = require('playwright');
const BASE = process.env.BASE_URL || 'http://localhost:3000';
require('fs').mkdirSync('./screenshots', { recursive: true });
const NAME = 'Khách E2E ' + Date.now().toString().slice(-5);
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 900 } });
  const errors = [];
  p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  p.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
  const shot = (n) => p.screenshot({ path: `./screenshots/${n}.png` });
  await p.goto(BASE + '/login');
  await p.fill('input[type=email]', 'manager@demo.local');
  await p.fill('input[type=password]', 'Demo@12345');
  await p.click('button[type=submit]');
  await p.waitForURL(BASE + '/');
  await p.waitForTimeout(1500);
  await shot('01-dashboard');
  console.log('realtime:', await p.locator('text=Realtime:').innerText());
  await p.goto(BASE + '/inbox');
  await p.waitForTimeout(1500);
  await p.click('button:has-text("Mô phỏng")');
  await p.fill('input[placeholder="vd. Nguyễn Văn A"]', NAME);
  await p.fill('textarea', 'Shop ơi giá giao hàng bao nhiêu vậy');
  await p.click('button:has-text("Gửi tin đến")');
  await p.waitForTimeout(800);
  await p.keyboard.press('Escape');
  await p.waitForSelector(`text=${NAME}`, { timeout: 10000 });
  await p.click(`li >> text=${NAME}`);
  await p.waitForTimeout(2500);
  await shot('02-conversation');
  const ta = p.locator('textarea[placeholder^="Nhập tin trả lời"]');
  await ta.fill('Dạ shop chào anh/chị, nhân viên E2E hỗ trợ ạ');
  await ta.press('Enter');
  await p.waitForTimeout(6000);
  await shot('03-after-send');
  const bubble = p.locator('text=Dạ shop chào anh/chị, nhân viên E2E hỗ trợ ạ').first();
  console.log('sent bubble visible:', await bubble.isVisible());
  console.log('statuses:', await p.locator('text=/· (Đã xem|Đã chuyển|Nền tảng đã nhận|Đang gửi)/').allInnerTexts());
  await p.click('button:has-text("Ghi chú nội bộ")');
  const nt = p.locator('textarea[placeholder="Ghi chú cho đồng nghiệp…"]');
  await nt.fill('Ghi chú E2E: khách hỏi phí ship');
  await p.click('button:has-text("Lưu ghi chú")');
  await p.waitForTimeout(1500);
  console.log('note visible:', await p.locator('text=Ghi chú E2E: khách hỏi phí ship').isVisible());
  await shot('04-note');
  for (const path of ['customers', 'canned', 'rules', 'ai', 'channels', 'members', 'reports', 'settings']) {
    await p.goto(BASE + '/' + path);
    await p.waitForTimeout(1800);
    await shot('page-' + path);
  }
  console.log('errors:', JSON.stringify(errors.slice(0, 10), null, 1));
  await b.close();
})().catch((e) => { console.error('FAIL', e.message); process.exit(1); });
